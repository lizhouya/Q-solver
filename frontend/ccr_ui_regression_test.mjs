import assert from 'node:assert/strict'
import fs from 'node:fs'

const provider = fs.readFileSync(new URL('./src/components/ProviderSelect.vue', import.meta.url), 'utf8')
assert.equal(provider.includes('connectionMode'), false, 'provider page must not expose connection mode')
assert.equal(provider.includes('update:connectionMode'), false)
assert.ok(provider.includes('CCR 本地网关'), 'CCR must remain a preset')
assert.ok(provider.includes('http://127.0.0.1:3456/v1'), 'CCR preset must use the canonical local root')
assert.ok(provider.includes("'select-preset'"), 'preset selection must emit draft-only intent')
const protocolSelect = provider.match(/<select[^>]*:value="apiProtocol"[^>]*>([\s\S]*?)<\/select>/)?.[1] || ''
assert.deepEqual([...protocolSelect.matchAll(/<option value="([^"]+)"/g)].map(match => match[1]), ['openai_chat', 'custom_json'], 'API UI must expose exactly two modes')
assert.equal(provider.includes('overview-card'), false, 'compact API form must not have an overview card')
const advanced = provider.match(/<details class="advanced-card">([\s\S]*?)<\/details>/)?.[1] || ''
const basic = provider.slice(0, provider.indexOf('<details'))
assert.ok(basic.includes('请求地址'))
assert.ok(basic.includes('API Key'))
assert.equal(basic.includes('Endpoint Path'), false, 'compatibility fields must be collapsed')
assert.equal(basic.includes('Response Format'), false)
assert.match(advanced, /v-if="apiProtocol === 'custom_json'"/)
assert.match(advanced, /v-if="apiProtocol === 'openai_chat'"/)
assert.ok(advanced.includes('Endpoint Path'), 'Chat endpoint remains editable without discarding old values')
assert.ok(advanced.includes('Response Format'))
for (const field of ['requestTemplate', 'responseJSONPointer', 'authHeader', 'authPrefix', 'extraHeadersText']) {
  assert.ok(advanced.includes(`:value="${field}"`), `${field} must be in collapsed advanced settings`)
  assert.ok(provider.includes(`'update:${field}'`), `${field} must emit a draft update`)
}
assert.match(provider, /<label[^>]*for="connection-url"/)
assert.match(provider, /<input[^>]*id="connection-url"/)
assert.match(provider, /<label[^>]*for="connection-key"/)
assert.match(provider, /<input[^>]*id="connection-key"[^>]*type="password"/)
assert.equal(/<details[^>]*\sopen(?:[\s>])/.test(provider), false, 'advanced settings start collapsed')
assert.equal(/(?:fetch|refreshModels|saveSettings|saveConnectionSettings)\(/.test(provider), false, 'mode/preset edits must not perform IO')
assert.ok(provider.includes('额外 Headers JSON'))
assert.ok(provider.includes('Response Format'))
assert.equal(provider.includes("connectionMode === 'ccr'"), false)

const model = fs.readFileSync(new URL('./src/components/ModelSelect.vue', import.meta.url), 'utf8')
assert.equal(model.includes('connectionMode'), false, 'model control must be protocol-neutral')
assert.ok(model.includes('filteredModels'), 'catalog model suggestions must be filtered locally')
assert.equal(model.includes('filteredSavedModels'), false, 'Revision C saved-model grouping must be removed')
assert.equal(model.includes('savedModels'), false)
assert.ok(model.includes('.includes(query)'), 'filter must use case-insensitive substring matching')
assert.ok(model.includes('const searchQuery = ref'), 'selected model and search query must remain separate')
assert.ok(model.includes("searchQuery.value = ''"))
assert.ok(model.includes('模型目录参考，非当前通道实测'))

const modal = fs.readFileSync(new URL('./src/components/SettingsModal.vue', import.meta.url), 'utf8')
assert.ok(modal.includes('模型与 API'))
assert.equal(modal.includes("ui.activeTab === 'model'"), false, 'separate model tab must be removed')
assert.equal(modal.includes('v-model:connectionMode'), false)
assert.equal(modal.includes('ensureCCRModelCatalog'), false, 'opening settings must not auto-fetch models')
assert.equal(modal.includes("tempSettings.connectionMode === 'ccr'"), false)
assert.ok(modal.includes('v-model:endpointPath="settingsStore.tempSettings.endpointPath"'))
assert.ok(modal.includes('v-model:extraHeadersText="settingsStore.extraHeadersText"'))
assert.ok(modal.includes('v-model:responseFormat="settingsStore.tempSettings.responseFormat"'))
for (const field of ['requestTemplate', 'responseJSONPointer', 'authHeader', 'authPrefix']) {
  assert.ok(modal.includes(`v-model:${field}="settingsStore.tempSettings.${field}"`), `${field} must bind to the shared draft`)
}
assert.ok(modal.includes(':default-custom-template="settingsStore.defaultCustomTemplate()"'))
assert.ok(modal.includes('settingsStore.legacyMigrationNotice'))
assert.match(modal, /:disabled="[^"]*!settingsStore.canRefreshModelCatalog/, 'custom mode refresh must be disabled')
assert.ok(modal.includes('自定义模板模式请手动填写模型'))
assert.ok(modal.includes('保存 API 设置'))
assert.ok(modal.includes('刷新候选模型'))
assert.ok(modal.includes('测试 API 连接'))
assert.ok(modal.includes('<details'))
assert.ok(modal.includes('图片实测'))
assert.ok(modal.includes('保存全部设置'))

console.log('CCR UI regression tests passed')
